const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('hce', {
  openHtml: () => ipcRenderer.invoke('file:open'),
  openDroppedHtml: (target, filePath) => ipcRenderer.invoke('file:open-dropped', target, filePath),
  getDroppedFilePath: (file) => webUtils.getPathForFile(file),
  openCompare: (side) => ipcRenderer.invoke('compare:open', side),
  reloadCompare: (side) => ipcRenderer.invoke('compare:reload', side),
  swapCompare: () => ipcRenderer.invoke('compare:swap'),
  getCompareState: () => ipcRenderer.invoke('compare:get-state'),
  analyzeCompare: () => ipcRenderer.invoke('compare:analyze'),
  editCompareText: (side, nodeId, value) => ipcRenderer.invoke('compare:edit-text', side, nodeId, value),
  mergeCompare: (mode, hunkId, direction) => ipcRenderer.invoke('compare:merge', mode, hunkId, direction),
  undoCompare: () => ipcRenderer.invoke('compare:undo'),
  redoCompare: () => ipcRenderer.invoke('compare:redo'),
  saveCompare: (side) => ipcRenderer.invoke('compare:save', side),
  applyEdits: (baseSource, edits) => ipcRenderer.invoke('html:apply-edits', baseSource, edits),
  formatText: (request) => ipcRenderer.invoke('html:format-selection', request),
  commitStyledText: (request) => ipcRenderer.invoke('html:commit-styled-text', request),
  tableOperation: (request) => ipcRenderer.invoke('html:table-operation', request),
  elementCandidates: (nodeId = null) => ipcRenderer.invoke('html:element-candidates', nodeId),
  deleteHtmlElement: (request) => ipcRenderer.invoke('html:delete-element', request),
  save: (workingSource) => ipcRenderer.invoke('file:save', workingSource),
  saveAs: (workingSource) => ipcRenderer.invoke('file:save-as', workingSource),
  diff: (workingSource) => ipcRenderer.invoke('html:diff', workingSource),
  diffAnalysis: (workingSource) => ipcRenderer.invoke('html:diff-analysis', workingSource),
  getSession: () => ipcRenderer.invoke('app:get-session'),
  getAppInfo: () => ipcRenderer.invoke('app:get-info'),
  copyPath: (target) => ipcRenderer.invoke('app:copy-path', target),
  openLink: (target) => ipcRenderer.invoke('app:open-link', target)
});
